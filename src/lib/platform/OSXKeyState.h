#include <set>
#include <vector>

class IOSXKeyResource;

//! OS X key state
/*!
A key state for OS X.
*/
class OSXKeyState : public KeyState
{
public:
  using KeyIDs = std::vector<KeyID>;

  OSXKeyState(IEventQueue *events, std::vector<std::string> layouts, bool isLangSyncEnabled);
  OSXKeyState(IEventQueue *events, deskflow::KeyMap &keyMap, std::vector<std::string> layouts, bool isLangSyncEnabled);
  ~OSXKeyState() override = default;

  //! @name modifiers
  //@{

  //! Handle modifier key change
  /*!
  Determines which modifier keys have changed and updates the modifier
  state and sends key events as appropriate.
  */
  void handleModifierKeys(void *target, KeyModifierMask oldMask, KeyModifierMask newMask);

  //@}
  //! @name accessors
  //@{

  //! Convert OS X modifier mask to deskflow mask
  /*!
  Returns the deskflow modifier mask corresponding to the OS X modifier
  mask in \p mask.
  */
  KeyModifierMask mapModifiersFromOSX(uint32_t mask) const;

  //! Convert CG flags-style modifier mask to old-style Carbon
  /*!
  Still required in a few places for translation calls.
  */
  KeyModifierMask mapModifiersToCarbon(uint32_t mask) const;

  //! Map key event to keys
  /*!
  Converts a key event into a sequence of KeyIDs and the shadow modifier
  state to a modifier mask.  The KeyIDs list, in order, the characters
  generated by the key press/release.  It returns the id of the button
  that was pressed or released, or 0 if the button doesn't map to a known
  KeyID.
  */
  KeyButton mapKeyFromEvent(KeyIDs &ids, KeyModifierMask *maskOut, CGEventRef event) const;

  //! Map key and mask to native values
  /*!
  Calculates mac virtual key and mask for a key \p key and modifiers
  \p mask.  Returns \c true if the key can be mapped, \c false otherwise.
  */
  bool
  mapDeskflowHotKeyToMac(KeyID key, KeyModifierMask mask, uint32_t &macVirtualKey, uint32_t &macModifierMask) const;

  //@}

  // IKeyState overrides
  bool fakeCtrlAltDel() override;
  bool fakeMediaKey(KeyID id) override;
  KeyModifierMask pollActiveModifiers() const override;
  int32_t pollActiveGroup() const override;
  void pollPressedKeys(KeyButtonSet &pressedKeys) const override;
  void updateKeyState() override;
  void fakeAllKeysUp() override;
  void releaseInjectedKeys(KeyModifierMask keep = 0) override;
  KeyModifierMask releaseGhostModifiers(KeyModifierMask candidates) override;
  KeyModifierMask pollReportedModifiers() const override;
  void setToggleState(KeyModifierMask bit, bool on) override;
  void sanitizeInjectedKeys() override;

  CGEventFlags getModifierStateAsOSXFlags() const;
  //! Flags for a posted pointer event (mouse move/button/scroll): only
  //! modifiers that a key is actually holding -- ours (ledgered) or a
  //! device-backed one on this machine's own keyboard. Never the bare
  //! shadow: a shadow bit that no key holds, re-stamped on every mouse
  //! move, is what kept a ghost modifier alive against its own release
  //! (2026-10-08 18:09, Ctrl: "live after release" still held).
  CGEventFlags pointerEventFlags() const;
  //! The OS flag word reduced to modifiers a key is holding (ledgered or
  //! device-backed); lock bits pass through. Every consumer of "what is
  //! held" on this platform goes through it.
  CGEventFlags heldModifierFlags() const;
  // Flags every posted key event carries: the shadow modifier state plus the
  // device-dependent bits. Public so tests can assert what an injected
  // letter would be composed against.
  CGEventFlags getKeyboardEventFlags() const;

  //! Seams for headless unit tests
  /*!
  Every OS touch point used by the modifier-reconciliation paths can be
  replaced so the logic runs without reading or injecting real input. An
  unset hook means "use the OS".
  */
  struct Hooks
  {
    // replaces CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState)
    std::function<CGEventFlags()> osModifierFlags;
    // replaces GetKeys() in pollPressedKeys
    std::function<void(KeyButtonSet &)> pressedKeys;
    // replaces IOHIDPostEvent; returns the kern_return_t of the post
    std::function<kern_return_t(uint8_t virtualKey, bool down, CGEventFlags flags)> postHIDKey;
    // replaces IOHIDGetModifierLockState; returns false when unavailable
    std::function<bool(bool &capsOn)> getCapsLockState;
    // replaces IOHIDSetModifierLockState; returns false on failure
    std::function<bool(bool capsOn)> setCapsLockState;
    // replaces monotonicSeconds() (the clock sanitizeInjectedKeys() judges
    // hardware-modifier freshness with)
    std::function<double()> monotonicNow;
    // replaces IsSecureEventInputEnabled(): while a password field owns
    // input the event tap sees no keyboard events at all, so the freshness
    // clock has no data and the stale-modifier sweep must not judge
    std::function<bool()> secureInputEnabled;
    // replaces CGEventSourceKeyState(kCGEventSourceStateHIDSystemState,
    // kVK_Function): a direct physical-state query used to reconcile the
    // tap-tracked physical-fn latch at boundaries (enter / secure-input off).
    std::function<bool()> physicalFnDown;
  };
  void setHooks(Hooks hooks);
  //! Primary re-entry resync: post NX_FLAGSCHANGED via IOHIDPostEvent with
  //! kIOHIDSetGlobalEventFlags and the ABSOLUTE flag word (same path as
  //! postHIDVirtualKey's modifier posts), and adopt it as the shadow.
  bool postModifierResync(uint16_t keycode, bool keyDown, uint64_t flags);


  //! Virtual keys of modifiers this process has injected and not yet released
  std::set<uint8_t> injectedModifiers() const;

  //! Secondary-only Fn/stray-modifier handling (stuck-Fn incident 2026-10-21).
  //@{
  //! Mark this a secondary (client) key state: only there do we clear/resync
  //! stray Fn and other modifier flags the OS word carries but no key holds.
  void setSecondaryScreen(bool secondary);
  //! Record whether the MacBook's own physical fn/Globe key (kVK_Function) is
  //! held, from a non-injected secondary-tap flagsChanged. Safe from the tap
  //! thread. A modifier post made while fn is down keeps SecondaryFn, and the
  //! stray sweep never clears a physically-held fn.
  void notePhysicalFnKey(bool held);
  //! Reconcile the physical-fn latch at a boundary where a release may have
  //! been missed (secondary enter, secure-input off): a physical-state query
  //! (Hooks::physicalFnDown / CGEventSourceKeyState) is authoritative, so the
  //! latch is set to whatever it reports -- a finger still on fn/Globe keeps
  //! it, a released one drops it. \p where names the boundary for the log.
  void reconcilePhysicalFnKey(const char *where);
  //! Whether the physical fn/Globe key is currently believed held (the latch
  //! bit, generation stripped). Exposed for tests.
  bool physicalFnHeld() const;
  //! Post a cleaned absolute flag word (via postModifierResync, kVK_Function
  //! up) when the OS word carries SecondaryFn that no held function-class key
  //! and no physical fn explains. No-op on the primary. Returns true iff it
  //! posted. Called after a modifier/function-key release and at enter/leave.
  bool clearStrayFnFlag();
  //! One stray-modifier timer tick on the secondary while on screen: sample
  //! the HID word, log stray-set changes, and -- when the same unexplained
  //! set survives two samples and the 1/s budget allows -- post a cleaned
  //! absolute word. Skipped under secure input. Returns true iff it posted.
  bool sampleStrayModifiers();
  //@}

  //! A modifier the OS reports down that no hardware flagsChanged backed
  //! within this many seconds is stale (K2: stranded by a crashed
  //! incarnation) and sanitizeInjectedKeys() releases it.
  static constexpr double kHardwareModifierFreshS = 2.0;

  //! Monotonic seconds (steady clock); the clock noteHardwareModifierFlags()
  //! stamps are expected in.
  static double monotonicSeconds();

  //! Record a flagsChanged seen by the event tap at \p now (monotonic
  //! seconds). Only the side-specific NX_DEVICE* bits count as evidence of
  //! a physical key. Safe to call from the tap thread.
  void noteHardwareModifierFlags(CGEventFlags flags, double now);

  //! Which OS X modifier flag a modifier virtual key drives (0 if none)
  static CGEventFlags modifierFlagForVirtualKey(uint8_t virtualKey);

  //! Tell the freshness clock whether hardware flagsChanged events can
  //! currently reach noteHardwareModifierFlags() at all (the event tap is
  //! installed and enabled). sanitizeInjectedKeys() judges a modifier stale
  //! only when hardware has been observable for the whole
  //! kHardwareModifierFreshS window: a tap that was down (epoch teardown,
  //! disabled-by-timeout) or blind (secure input) leaves the stamps old for
  //! a key the user is really holding. Safe to call from the tap thread.
  void noteHardwareObservation(bool observing, double now);

  //! True when hardware presses have been observable for \p seconds up to
  //! \p at (see noteHardwareObservation)
  bool hardwareObservableFor(double seconds, double at) const;

  //! Whether a password field currently owns keyboard input (hookable)
  bool secureInputEnabled() const;

protected:
  // KeyState overrides
  void getKeyMap(deskflow::KeyMap &keyMap) override;
  void fakeKey(const Keystroke &keystroke) override;

private:
  class KeyResource;

  void getKeyMapImpl(deskflow::KeyMap &keyMap);

  // Add hard coded special keys to a deskflow::KeyMap.
  void getKeyMapForSpecialKeys(deskflow::KeyMap &keyMap, int32_t group) const;

  // Convert keyboard resource to a key map
  bool getKeyMap(deskflow::KeyMap &keyMap, int32_t group, const IOSXKeyResource &r) const;

  // Get the available keyboard groups
  bool getGroups(AutoCFArray &) const;

  // Change active keyboard group to group
  void setGroup(int32_t group);

  // Send an event for the given modifier key
  void handleModifierKey(void *target, uint32_t virtualKey, KeyID id, bool down, KeyModifierMask newMask);

  // Checks if any in \p ids is a glyph key and if \p isCommand is false.
  // If so it adds the AltGr modifier to \p mask.  This allows OS X
  // servers to use the option key both as AltGr and as a modifier.  If
  // option is acting as AltGr (i.e. it generates a glyph and there are
  // no command modifiers active) then we don't send the super modifier
  // to clients because they'd try to match it as a command modifier.
  void adjustAltGrModifier(const KeyIDs &ids, KeyModifierMask *mask, bool isCommand) const;

  // Maps an OS X virtual key id to a KeyButton.  This simply remaps
  // the ids so we don't use KeyButton 0.
  static KeyButton mapVirtualKeyToKeyButton(uint32_t keyCode);

  // Maps a KeyButton to an OS X key code.  This is the inverse of
  // mapVirtualKeyToKeyButton.
  static uint32_t mapKeyButtonToVirtualKey(KeyButton keyButton);

  void init();

  // Post a key event to HID manager. It posts an event to HID client, a
  // much lower level than window manager which's the target from carbon
  // CGEventPost
  kern_return_t postHIDVirtualKey(uint8_t virtualKeyCode, bool postDown);

  CGEventFlags getDeviceDependedFlags() const;

  void setKeyboardModifiers(CGKeyCode virtualKey, bool keyDown);

  void postKeyboardKey(CGKeyCode virtualKey, bool keyDown);

  // OS truth for the modifier flags (hookable)
  //
  // K6 investigation finding: CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState)
  // is a direct HID-state poll, not an event-tap read, and Apple does not
  // document it as blinded by secure input (unlike the event tap, which
  // secureInputEnabled() exists to work around). No evidence was found
  // either way from a real SecurityAgent dialog. Do NOT add a secure-input
  // branch here (or in modifierEventFlags() below) on that assumption alone
  // -- if a future incident shows this call going stale/wrong under secure
  // input, that would be new evidence, not something this comment predicts.
  CGEventFlags osModifierFlags() const;

  // Post the Up for every ledgered modifier the OS (\p os) still reports
  // down (Caps: always, it is a key not the lock) and drop it from the
  // ledger. Ledger entries whose modifier flag is in \p keep are left
  // untouched. Shared by sanitizeInjectedKeys(), releaseInjectedKeys() and
  // fakeAllKeysUp(). Callers reseed the shadow flags first.
  void releaseLedgeredModifiers(CGEventFlags os, CGEventFlags keep = 0);

  // Overwrite the shadow modifier flags with what the OS reports so the
  // next posted event carries the real global flags, not stale ones.
  void reseedShadowFlagsFromOS();

  // Shadow modifier flags from an explicit flag word (what we just posted
  // as the global flags, so getKeyboardEventFlags() agrees with the OS).
  void setShadowFlags(CGEventFlags flags);

  // The global flag word a modifier virtual key's Down/Up must carry.
  // IOHIDPostEvent(..., kIOHIDSetGlobalEventFlags) REPLACES the system's
  // modifier flags with the word we post, so: LIVE OS flags for every bit
  // that is not ours (a physical key the shadow never saw survives), the
  // LEDGER for ours. Every modifier we hold (m_injectedModifiers) is forced
  // on, the key being posted is forced to its new state, and a key whose Up
  // we posted but the OS has not adopted yet (m_pendingReleases) is forced
  // off -- otherwise a Shift-Up / Control-Down pair posted back-to-back
  // re-asserted the Shift the live read still showed. The generic bit is
  // cleared only when no right-hand device bit still holds it; a Caps Up
  // keeps the lock state.
  //
  // Same-side limitation: we only ever post the LEFT virtual keys, and the
  // device bits cannot tell our left Shift from the user's left Shift. A
  // physical left Shift held while we release our injected left Shift is
  // cleared with it (it self-corrects on the user's next Shift edge); only
  // a right-hand modifier is protected through a release of ours.
  //
  // K6: this is the live per-keystroke path (every posted key composes its
  // flags here) and it has NO secure-input awareness -- see the comment on
  // osModifierFlags() above for why that is deliberate, not an oversight.
  CGEventFlags modifierEventFlags(uint8_t virtualKey, bool down) const;
  static CGEventFlags leftDeviceBitForVirtualKey(uint8_t virtualKey);
  static CGEventFlags rightDeviceBitForVirtualKey(uint8_t virtualKey);

  // Caps lock state via IOHIDSystem (hookable). Return false when unknown.
  bool getCapsLockState(bool &on) const;
  bool setCapsLockState(bool on);

  // Keep the tracked modifier mask (KeyState::m_mask) in step with a lock
  // bit the OS now reports.
  void syncTrackedModifier(KeyModifierMask bit, bool on);

  // Current monotonic time (hookable).
  double now() const;

  // Index into m_lastHardwareModifierAt for a modifier virtual key, or -1.
  static int hardwareSlotForVirtualKey(uint8_t virtualKey);

  // Compose the global flag word a post must carry: the live OS word
  // reconciled against our ledger -- pending releases forced off, held
  // modifiers forced on, and (when forcePostedKey) the posted key's new state
  // applied last. The reconciliation modifierEventFlags() and the Fn cleanup
  // share, so neither re-asserts a modifier a stale OS read still shows.
  CGEventFlags composeModifierWord(uint8_t virtualKey, bool down, bool forcePostedKey) const;
  // Drop a stray SecondaryFn / NumericPad bit from \p flags (secondary only,
  // item 5): one that no key -- injected (and still fresh) or physically down
  // -- legitimately holds.
  void stripStrayFnNumericPad(CGEventFlags &flags) const;
  // Which carrier bits a key currently holds: any injected carrier still in
  // m_injectedKeys (until its up / fakeAllKeysUp at leave), plus the MacBook's
  // own physical carrier / fn key (GetKeys), excluding keys we injected.
  void carriersHeld(bool &fnHeld, bool &numpadHeld) const;
  // True iff an injected (still-held) non-modifier key is Fn-carrying; decides
  // whether a release was the last injected Fn carrier.
  bool holdingFnCarryingKey() const;
  // Diagnostics only (count, no key id): log once per hold if an injected
  // function-class key has been held past the long-hold threshold with no
  // repeat. Called from the sampler tick.
  void logLongHeldFunctionKeys();
  // Physical-state query for the fn/Globe key (kVK_Function), hookable; backs
  // reconcilePhysicalFnKey().
  bool physicalFnDown() const;

private:
  // OS X uses a physical key if 0 for the 'A' key.  deskflow reserves
  // KeyButton 0 so we offset all OS X physical key ids by this much
  // when used as a KeyButton and by minus this much to map a KeyButton
  // to a physical button.
  enum
  {
    KeyButtonOffset = 1
  };

  using GroupMap = std::map<CFDataRef, int32_t>;
  using VirtualKeyMap = std::map<uint32_t, KeyID>;

  // Refresh m_activeGroupCache from the current TIS keyboard layout. MUST run
  // on the main dispatch queue -- macOS 14+ asserts the main queue inside the
  // Text Input Source APIs, so calling them off the deskflow event thread
  // crashes via _dispatch_assert_queue_fail.
  int32_t updateActiveGroupCache();

  VirtualKeyMap m_virtualKeyMap;
  mutable uint32_t m_deadKeyState;
  AutoCFArray m_groups{nullptr, CFRelease};
  GroupMap m_groupMap;
  // Last keyboard group resolved on the main queue. pollActiveGroup() reads
  // this off the event thread (where the TIS calls would crash) and kicks an
  // async refresh; on the main thread it refreshes synchronously.
  mutable std::atomic<int32_t> m_activeGroupCache{0};
  bool m_shiftPressed;
  bool m_controlPressed;
  bool m_altPressed;
  bool m_superPressed;
  bool m_capsPressed;
  // modifier virtual keys this process posted Down for and has not yet
  // posted Up for; the only modifiers sanitizeInjectedKeys() may release.
  std::set<uint8_t> m_injectedModifiers;
  // modifier virtual keys whose Up we posted and whose left device bit the
  // live flags still showed at the last post (the OS had not adopted it);
  // forced off in modifierEventFlags() until the live flags drop it
  std::set<uint8_t> m_pendingReleases;
  // non-modifier keys this process posted Down for and has not posted Up for.
  // modifierEventFlags() keeps the live Fn/NumericPad bits only while one of
  // these holds them; cleared in fakeAllKeysUp() after the releases.
  // Event-thread only (fakeKey / the stray timer tick).
  std::set<uint8_t> m_injectedKeys;
  // monotonic time each injected non-modifier key was last posted Down (or
  // repeated) and the function-class keys already long-hold-logged this hold;
  // used ONLY by the long-hold diagnostic, not to explain Fn. Event-thread only.
  std::map<uint8_t, double> m_injectedKeyAt;
  std::set<uint8_t> m_longHoldLogged;
  // the MacBook's own physical fn/Globe key, tracked from the secondary tap
  // thread; read when composing/resyncing flags. Generation-tagged so a tap
  // observation (notePhysicalFnKey) landing mid-reconcile always wins: bit 0 is
  // "held", bits 1.. are a generation the tap bumps on every write, and the
  // boundary reconcile only stores its query result if the generation it read
  // is still current (else the tap's newer observation stands). See
  // reconcilePhysicalFnKey().
  std::atomic<uint32_t> m_physicalFn{0};
  // true on a secondary (client) key state: gates the Fn-clear and the
  // stray-modifier resync so the primary keeps its current behaviour.
  std::atomic<bool> m_isSecondaryScreen{false};
  // stray-modifier timer bookkeeping (event-thread only): the two-sample
  // dwell, the monotonic time of the last resync post (1/s budget), and the
  // last stray set logged by the change-only [cmd-diag] sampler.
  deskflow::platform::StrayDwell m_strayDwell;
  double m_lastStrayResyncAt = std::numeric_limits<double>::lowest();
  double m_lastStrayLogAt = std::numeric_limits<double>::lowest();
  uint64_t m_lastLoggedStray = 0;
  bool m_haveLoggedStray = false;
  // monotonic time a hardware flagsChanged last carried each modifier's
  // side-specific device bit (shift, control, alt, super); written on the
  // event-tap thread, read by sanitizeInjectedKeys()
  std::array<std::atomic<double>, 4> m_lastHardwareModifierAt{
      std::numeric_limits<double>::lowest(), std::numeric_limits<double>::lowest(),
      std::numeric_limits<double>::lowest(), std::numeric_limits<double>::lowest()
  };
  // whether hardware flagsChanged events can reach the freshness clock, and
  // since when (monotonic seconds). Defaults to "observable since forever"
  // so a bare OSXKeyState (tests, tools) keeps the sweep; OSXScreen owns
  // the real value around the event tap's lifetime.
  std::atomic<bool> m_hardwareObservable{true};
  std::atomic<double> m_hardwareObservableSince{std::numeric_limits<double>::lowest()};
  Hooks m_hooks;
};
